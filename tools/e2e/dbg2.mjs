import { chromium } from 'playwright-core';
import http from 'node:http'; import fs from 'node:fs'; import path from 'node:path';
const ROOT='/home/ky/dev/power_grid_game_qwen_flash_next';
const MIME={'.html':'text/html; charset=utf-8','.js':'text/javascript; charset=utf-8','.css':'text/css; charset=utf-8'};
const srv=http.createServer((q,r)=>{const u=decodeURIComponent(q.url.split('?')[0]);const f=path.join(ROOT,u==='/'?'index.html':u);if(!fs.existsSync(f)||fs.statSync(f).isDirectory()){r.writeHead(404);r.end();return;}r.writeHead(200,{'content-type':MIME[path.extname(f)]||'text/plain'});fs.createReadStream(f).pipe(r);});
await new Promise(res=>srv.listen(8147,'127.0.0.1',res));
const b=await chromium.launch({executablePath:'/usr/local/bin/chromium',args:['--no-sandbox','--disable-dev-shm-usage']});
const p=await b.newPage();
p.on('pageerror',e=>console.log('PAGEERROR:', (e.stack||String(e)).split('\n').slice(0,6).join('\n')));
p.on('console',m=>{if(m.type()==='error')console.log('CONSOLE-ERR:',m.text());});
await p.goto('http://127.0.0.1:8147/');
await p.waitForTimeout(600);
await p.click('[data-a="new"]');
await p.waitForTimeout(1500);
console.log('state:', await p.evaluate(()=>{const g=window.__gridling.state();return {tick:g.tick,speed:window.__gridling.ui.speed,modalOpen:window.__gridling.ui.modalOpen,coach:window.__gridling.ui.coachStep,geo:window.__gridling.ui.geo&&{...window.__gridling.ui.geo, ctx:undefined}};}));
console.log('canvas size:', await p.evaluate(()=>{const c=document.getElementById('map');return {w:c.width,h:c.height,cw:c.clientWidth,ch:c.clientHeight};}));
await p.waitForTimeout(1500);
console.log('after wait, tick:', await p.evaluate(()=>window.__gridling.state().tick));
await b.close(); srv.close();
