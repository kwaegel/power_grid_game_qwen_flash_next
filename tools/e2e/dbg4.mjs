import { chromium } from 'playwright-core';
import http from 'node:http'; import fs from 'node:fs'; import path from 'node:path';
const ROOT='/home/ky/dev/power_grid_game_qwen_flash_next';
const MIME={'.html':'text/html; charset=utf-8','.js':'text/javascript; charset=utf-8','.css':'text/css; charset=utf-8'};
const srv=http.createServer((q,r)=>{const u=decodeURIComponent(q.url.split('?')[0]);const f=path.join(ROOT,u==='/'?'index.html':u);if(!fs.existsSync(f)){r.writeHead(404);r.end();return;}r.writeHead(200,{'content-type':MIME[path.extname(f)]||'text/plain'});fs.createReadStream(f).pipe(r);});
await new Promise(res=>srv.listen(8151,'127.0.0.1',res));
const b=await chromium.launch({executablePath:'/usr/local/bin/chromium',args:['--no-sandbox','--disable-dev-shm-usage']});
const p=await b.newPage({viewport:{width:1440,height:900}});
p.on('pageerror',e=>console.log('PAGEERROR',String(e)));
await p.goto('http://127.0.0.1:8151/');
await p.waitForTimeout(400);
await p.click('[data-a="new"]');
await p.waitForTimeout(600);
const raf = await p.evaluate(()=>new Promise(res=>{let n=0;const t0=performance.now();const f=()=>{n++;if(performance.now()-t0<2000)requestAnimationFrame(f);else res({frames:n,ms:performance.now()-t0});};requestAnimationFrame(f);}));
console.log('rAF frames in 2 s:', raf);
await p.evaluate(()=>{window.__gridling.ui.coachStep=-1; document.getElementById('coach').hidden=true; window.__gridling.setSpeed(4); window.__gridling.setTps(8);});
const t0=await p.evaluate(()=>window.__gridling.state().tick);
await p.waitForTimeout(3000);
const t1=await p.evaluate(()=>({tick:window.__gridling.state().tick, speed:window.__gridling.ui.speed, modal:window.__gridling.ui.modalOpen, tpsOK:true}));
console.log('ticks advanced in 3 s at 4x:', t0, '->', t1);
await b.close(); srv.close();
